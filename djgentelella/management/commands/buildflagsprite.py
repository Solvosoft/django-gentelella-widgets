"""Regenerate the committed flag sprite.

This is a *maintenance* command, not a build step: the sprite it writes,
``static/gentelella/flags/flags.4x3.svg.gz``, is committed to the repository and
shipped as-is. Run it only when ``FLAG_ICONS_VERSION`` is bumped.

The alternative it replaces was downloading 533 files from a CDN on every
``loaddevstatic`` and base64-inlining them into a 6.35 MB stylesheet, which the
browser had to load in full to show a single flag.
"""
